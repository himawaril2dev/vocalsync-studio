#!/usr/bin/env node
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const TAURI_DIR = join(ROOT, "src-tauri");
const HOME = resolve(os.homedir());
const CARGO_CONFIG_DIR = join(TAURI_DIR, ".cargo");
const CARGO_CONFIG = join(CARGO_CONFIG_DIR, "config.toml");

const remapPrefixes = [
  [ROOT, "app-src"],
  [join(HOME, ".cargo", "registry", "src"), "cargo-registry"],
  [join(HOME, ".cargo", "git", "checkouts"), "cargo-git"],
  [join(HOME, ".rustup", "toolchains"), "rust-toolchains"],
  [HOME, "user-home"],
].filter(([path]) => existsSync(path));

const remapFlags = remapPrefixes.map(([path, replacement]) => `--remap-path-prefix=${path}=${replacement}`);

const previousCargoConfig = existsSync(CARGO_CONFIG) ? readFileSync(CARGO_CONFIG, "utf8") : null;

function tomlLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function writeTemporaryCargoConfig() {
  mkdirSync(CARGO_CONFIG_DIR, { recursive: true });
  writeFileSync(
    CARGO_CONFIG,
    [
      "# Generated by scripts/tauri-build-release.mjs; do not commit.",
      "[build]",
      "rustflags = [",
      ...remapFlags.map((flag) => `  ${tomlLiteral(flag)},`),
      "]",
      "",
    ].join("\n"),
    "utf8",
  );
}

function cleanupTemporaryCargoConfig() {
  if (previousCargoConfig !== null) {
    writeFileSync(CARGO_CONFIG, previousCargoConfig, "utf8");
    return;
  }
  rmSync(CARGO_CONFIG, { force: true });
  try {
    rmSync(CARGO_CONFIG_DIR, { recursive: false, force: true });
  } catch {
    // The directory can remain when Cargo creates another file under it.
  }
}

console.log("Building Tauri release with local path remapping enabled.");
writeTemporaryCargoConfig();

const child = spawn(process.platform === "win32" ? "npm.cmd" : "npm", ["run", "tauri", "--", "build"], {
  cwd: ROOT,
  env: process.env,
  stdio: "inherit",
  shell: process.platform === "win32",
});

child.on("error", (err) => {
  cleanupTemporaryCargoConfig();
  console.error(err.message);
  process.exit(1);
});

child.on("exit", (code) => {
  cleanupTemporaryCargoConfig();
  process.exit(code ?? 1);
});
